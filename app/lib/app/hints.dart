/// Convenience widget: `hintFor('routing_mode')`.
Widget hintFor(String key, {double size = 18}) {
  final h = kHints[key];
  if (h == null) return const SizedBox.shrink();
  return InfoHint(title: h.title, body: h.body, size: size);
}

/// Record form for [LabeledHint].
({String title, String body}) hintRecord(String key) {
  final h = kHints[key] ?? const Hint('', '');
  return (title: h.title, body: h.body);
}
